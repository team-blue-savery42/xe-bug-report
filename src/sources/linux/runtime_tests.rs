//! Unit tests for `src/sources/linux/runtime.rs`.

use std::time::Duration;

use super::*;

fn exited(code: i32, output: &str) -> ChildResult {
    ChildResult {
        outcome: ChildOutcome::Exited(code),
        output: output.as_bytes().to_vec(),
        truncated: false,
        elapsed: Duration::ZERO,
    }
}

fn outcome(outcome: ChildOutcome) -> ChildResult {
    ChildResult { outcome, output: Vec::new(), truncated: false, elapsed: Duration::ZERO }
}

const LDCONFIG: &str = "1234 libs found in cache `/etc/ld.so.cache'
\tlibze_loader.so.1 (libc6,x86-64) => /usr/lib/libze_loader.so.1
\tlibze_intel_gpu.so.1 (libc6,x86-64) => /usr/lib/libze_intel_gpu.so.1
\tlibz.so.1 (libc6,x86-64) => /usr/lib/libz.so.1
\tlibigc.so.2 (libc6,x86-64) => /usr/lib/libigc.so.2
\tlibigccmcompiler.so (libc6,x86-64) => /usr/lib/libigccmcompiler.so
\tlibOpenCL.so.1 (libc6) => /usr/lib32/libOpenCL.so.1
\tlibopencl-clang.so.22.1 (libc6,x86-64) => /usr/lib/libopencl-clang.so.22.1
\tlibze_validation_layer.so.1 => /opt/l0/libze_validation_layer.so.1
Cache generated by: ldconfig (GNU libc) stable release version 2.42
";

#[test]
fn the_runtime_library_set() {
    for name in [
        "libigc.so.2",
        "libigdfcl.so.2",
        "libiga64.so.2",
        "libopencl-clang.so.22.1",
        "libze_intel_gpu.so.1",
        "libze_loader.so",
        "libze_validation_layer.so.1",
        "libigdgmm.so.12",
        "libOpenCL.so.1",
    ] {
        assert!(is_runtime_library(name), "{name}");
    }
    for name in ["libigccmcompiler.so", "libz.so.1", "libze_tracing_layer.so.1", "libopencl.so", "libigc"] {
        assert!(!is_runtime_library(name), "{name}");
    }
}

#[test]
fn ldconfig_lines_parse_into_name_tags_and_path() {
    let entries = parse_ldconfig(LDCONFIG);
    assert_eq!(entries.len(), 8, "{entries:?}");
    assert_eq!(
        entries[0],
        CacheEntry {
            name: "libze_loader.so.1".into(),
            tags: "libc6,x86-64".into(),
            path: "/usr/lib/libze_loader.so.1".into()
        }
    );
    assert_eq!(entries[5].tags, "libc6");
    let untagged = &entries[7];
    assert_eq!((untagged.name.as_str(), untagged.tags.as_str()), ("libze_validation_layer.so.1", ""));
    assert!(parse_ldconfig("").is_empty());
    assert!(parse_ldconfig(" => \n=>\nlibx.so => \n").is_empty());
}

#[test]
fn libraries_are_listed_with_the_file_they_resolve_to() {
    let text = format_libraries(&exited(0, LDCONFIG), |path| match path.to_str() {
        Some("/usr/lib/libze_loader.so.1") => Ok(PathBuf::from("/usr/lib/libze_loader.so.1.32.0")),
        Some("/usr/lib/libigc.so.2") => Ok(PathBuf::from("/usr/lib/libigc.so.2.41.0+0")),
        Some("/opt/l0/libze_validation_layer.so.1") => {
            Ok(PathBuf::from("/opt/l0/libze_validation_layer.so.1"))
        }
        _ => Err("No such file or directory (os error 2)".to_owned()),
    });
    assert!(
        text.contains(
            "  libze_loader.so.1 (libc6,x86-64) => /usr/lib/libze_loader.so.1 -> /usr/lib/libze_loader.so.1.32.0\n"
        ),
        "{text}"
    );
    assert!(
        text.contains("libigc.so.2 (libc6,x86-64) => /usr/lib/libigc.so.2 -> /usr/lib/libigc.so.2.41.0+0\n")
    );
    assert!(
        text.contains("libze_validation_layer.so.1 => /opt/l0/libze_validation_layer.so.1 -> (not a link)\n")
    );
    assert!(text.contains(
        "libze_intel_gpu.so.1 (libc6,x86-64) => /usr/lib/libze_intel_gpu.so.1 -> (unresolved: No such file"
    ));
    assert!(!text.contains("libz.so") && !text.contains("libigccmcompiler"), "{text}");
}

#[test]
fn an_unusable_loader_cache_is_said_so() {
    let ok = |_: &Path| Ok(PathBuf::new());
    assert!(format_libraries(&exited(0, "nothing\n"), ok).ends_with("  none\n"));
    assert!(format_libraries(&outcome(ChildOutcome::NotFound), ok).ends_with("  ldconfig not installed\n"));
    assert!(format_libraries(&outcome(ChildOutcome::TimedOut), ok).contains("did not finish within 10 s"));
    assert!(format_libraries(&exited(1, ""), ok).contains("ldconfig -p: exit code 1"));
    let mut cut = exited(0, LDCONFIG);
    cut.truncated = true;
    assert!(format_libraries(&cut, ok).contains("cut at its size cap"));
}

#[test]
fn the_ocloc_version_or_why_there_is_none() {
    assert_eq!(format_ocloc(&exited(0, "26.35.39758\n")), "ocloc --version:\n  26.35.39758\n");
    assert_eq!(format_ocloc(&outcome(ChildOutcome::NotFound)), "ocloc --version: ocloc not installed\n");
    assert_eq!(format_ocloc(&exited(2, "bad\n")), "ocloc --version: exit code 2\n  bad\n");
    assert!(format_ocloc(&outcome(ChildOutcome::TimedOut)).contains("did not finish within 10 s"));
    assert!(
        format_ocloc(&outcome(ChildOutcome::SpawnFailed("denied".into())))
            .contains("could not start: denied")
    );
}

#[test]
fn the_source_runs_the_given_ldconfig_and_names_both_commands() {
    // A loader cache tool that does not exist: the report still has both parts.
    let produced =
        gpu_runtime("system/gpu-runtime.txt", &["/nonexistent/ldconfig".to_owned(), "-p".to_owned()]);
    assert_eq!(produced.len(), 1);
    let text = String::from_utf8_lossy(&produced[0].data);
    assert!(text.starts_with("ocloc --version"), "{text}");
    assert!(text.contains("GPU runtime libraries in the loader cache"), "{text}");
    assert_eq!(produced[0].via, "ocloc --version; /nonexistent/ldconfig -p");
}
